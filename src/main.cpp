    AppendMenuW(m, MF_STRING, ID_SUPPORT, L"Support the project...");
    AppendMenuW(m, MF_SEPARATOR, 0, nullptr);
    AppendMenuW(m, MF_STRING, ID_EXIT, L"Exit");
